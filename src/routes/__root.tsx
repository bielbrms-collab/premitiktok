import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import {
  Outlet,
  Link,
  createRootRouteWithContext,
  useRouter,
  useRouterState,
  HeadContent,
  Scripts,
} from "@tanstack/react-router";
import { useEffect, type ReactNode } from "react";

import appCss from "../styles.css?url";
import { reportLovableError } from "../lib/lovable-error-reporting";
import { TIKTOK_PIXEL_SNIPPET, ttqPage } from "../lib/tiktok-pixel";
import { Toaster } from "@/components/ui/sonner";

function NotFoundComponent() {
  return (
    <div className="flex min-h-screen items-center justify-center bg-background px-4">
      <div className="max-w-md text-center">
        <h1 className="text-7xl font-bold text-foreground">404</h1>
        <h2 className="mt-4 text-xl font-semibold text-foreground">Pagina non trovata</h2>
        <p className="mt-2 text-sm text-muted-foreground">
          La pagina che stai cercando non esiste o è stata spostata.
        </p>
        <div className="mt-6">
          <Link
            to="/"
            className="inline-flex items-center justify-center rounded-md bg-primary px-4 py-2 text-sm font-medium text-primary-foreground transition-colors hover:bg-primary/90"
          >
            Torna alla home
          </Link>
        </div>
      </div>
    </div>
  );
}

function ErrorComponent({ error, reset }: { error: Error; reset: () => void }) {
  console.error(error);
  const router = useRouter();
  useEffect(() => {
    reportLovableError(error, { boundary: "tanstack_root_error_component" });
  }, [error]);

  return (
    <div className="flex min-h-screen items-center justify-center bg-background px-4">
      <div className="max-w-md text-center">
        <h1 className="text-xl font-semibold tracking-tight text-foreground">
          Non è stato possibile caricare questa pagina
        </h1>
        <p className="mt-2 text-sm text-muted-foreground">
          Si è verificato un errore da parte nostra. Riprova o torna alla home.
        </p>
        <div className="mt-6 flex flex-wrap justify-center gap-2">
          <button
            onClick={() => {
              router.invalidate();
              reset();
            }}
            className="inline-flex items-center justify-center rounded-md bg-primary px-4 py-2 text-sm font-medium text-primary-foreground transition-colors hover:bg-primary/90"
          >
            Riprova
          </button>
          <a
            href="/"
            className="inline-flex items-center justify-center rounded-md border border-input bg-background px-4 py-2 text-sm font-medium text-foreground transition-colors hover:bg-accent"
          >
            Torna alla home
          </a>
        </div>
      </div>
    </div>
  );
}

export const Route = createRootRouteWithContext<{ queryClient: QueryClient }>()({
  head: () => ({
    meta: [
      { charSet: "utf-8" },
      { name: "viewport", content: "width=device-width, initial-scale=1" },
      { title: "TikTok Ricompense | Prelievo e pagamenti" },
      { name: "description", content: "Percorso di prelievo, pagamento sicuro e pagine di conferma TikTok Ricompense." },
      { name: "author", content: "TikTok Ricompense" },
      { property: "og:title", content: "TikTok Ricompense" },
      { property: "og:description", content: "Percorso di prelievo, pagamento sicuro e pagine di conferma." },
      { property: "og:type", content: "website" },
      { name: "twitter:card", content: "summary_large_image" },
      { name: "twitter:site", content: "@Lovable" },
    ],
    links: [
      {
        rel: "stylesheet",
        href: appCss,
      },
      { rel: "icon", href: "/favicon.ico", type: "image/x-icon" },
      { rel: "preconnect", href: "https://analytics.tiktok.com" },
      { rel: "preconnect", href: "https://api.cooud.com" },
      { rel: "preconnect", href: "https://cdn.cooud.com" },
    ],
    scripts: [{ children: TIKTOK_PIXEL_SNIPPET }],
  }),
  shellComponent: RootShell,
  component: RootComponent,
  notFoundComponent: NotFoundComponent,
  errorComponent: ErrorComponent,
});

function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="it">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const pathname = useRouterState({ select: (s) => s.location.pathname });

  // Pageview do TikTok Pixel a cada navegação client-side.
  useEffect(() => {
    ttqPage();
  }, [pathname]);

  return (
    <QueryClientProvider client={queryClient}>
      <nav aria-label="Preview routes" className="sr-only" data-lovable-preview-routes="true">
        <Link to="/">Home</Link>
        <Link to="/pressel">Pressel</Link>
        <Link to="/back-redirect">Back Redirect</Link>
        <Link to="/checkout">Checkout</Link>
        <Link to="/obrigado">Grazie</Link>
        <Link to="/obrigado2">Grazie 2</Link>
        <Link to="/obrigado3">Grazie 3</Link>
        <Link to="/obrigado4">Grazie 4</Link>
      </nav>
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <Outlet />
      <Toaster richColors position="top-right" />
    </QueryClientProvider>
  );
}
